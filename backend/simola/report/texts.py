class Words:
    """The texts of one language, with its number and date formats."""

    def __init__(self, lang: Lang) -> None:
        self.lang = lang
        self._t = TEXTS[lang]

    def __call__(self, key: str, count: int | None = None, **kw: object) -> str:
        entry = self._t[key]
        if isinstance(entry, tuple):
            entry = entry[0] if count == 1 else entry[1]
        return entry.format(**kw) if kw else entry

    # ---- numbers: grouping and decimal marks as on the dashboard (Intl en-GB / id-ID)
    def integer(self, n: int | None) -> str:
        if n is None:
            return "—"
        s = f"{abs(n):,}"
        s = s.replace(",", ".") if self.lang == "id" else s
        return f"−{s}" if n < 0 else s  # a real minus sign

    def pct(self, p: float | None) -> str:
        """99.84 / 99,84; the API has already rounded half up to two decimals (FR-KPI-007)."""
        if p is None:
            return "—"
        s = f"{p:,.2f}"
        return s.translate(str.maketrans(",.", ".,")) if self.lang == "id" else s

    def num(self, v: float, digits: int) -> str:
        """A plain number with a fixed number of decimals (chart axes)."""
        s = f"{v:,.{digits}f}"
        return s.translate(str.maketrans(",.", ".,")) if self.lang == "id" else s

    # ---- dates and times (UTC)
    def month(self, d: date) -> str:
        return f"{MONTHS[self.lang][d.month - 1]} {d.year}"

    def day_long(self, d: date) -> str:
        return f"{d.day} {MONTHS[self.lang][d.month - 1]} {d.year}"

    def day_short(self, d: date) -> str:
        return f"{d.day} {MONTHS_SHORT[self.lang][d.month - 1]}"

    @staticmethod
    def time(t: datetime) -> str:
        return t.strftime("%Y-%m-%d %H:%M")

    @staticmethod
    def iso_day(d: date) -> str:
        return d.isoformat()

    def duration(self, minutes: int) -> str:
        d, rest = divmod(minutes, 1440)
        h, m = divmod(rest, 60)
        if d:
            return self("dur_days", d=d, h=h)
        if h:
            return self("dur_hours", h=h, m=m) if m else self("dur_hours_only", h=h)
        return self("dur_minutes", m=m)

    def days_list(self, days: list[date]) -> str:
        """1–23 Oct, 25 Oct: runs of consecutive days joined with an en dash."""
        runs: list[tuple[date, date]] = []
        for d in sorted(days):
            if runs and (d - runs[-1][1]).days == 1:
                runs[-1] = (runs[-1][0], d)
            else:
                runs.append((d, d))
        parts = [
            self.day_short(a)
            if a == b
            else f"{a.day}–{self.day_short(b)}"
            if a.month == b.month
            else f"{self.day_short(a)} – {self.day_short(b)}"
            for a, b in runs
        ]
        return ", ".join(parts)
